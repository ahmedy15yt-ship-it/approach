export function normalizeWhiteboardLessonScript(
  raw: any,
  params: WhiteboardGenerationParams,
  meta: { source: 'gemini' | 'fallback'; providerLabel?: string; warning?: string }
): WhiteboardLessonScript | null {
  if (!raw || typeof raw !== 'object' || !Array.isArray(raw.scenes) || raw.scenes.length === 0) {
    return null;
  }

  const defaultDiagram = inferDiagramType(params.subject, params.chapter, params.lesson);
  const scenes: WhiteboardScene[] = raw.scenes
    .slice(0, 6)
    .map((sc: any, idx: number): WhiteboardScene => {
      const diag: WhiteboardDiagramType = VALID_DIAGRAM_TYPES.has(sc?.diagramType)
        ? sc.diagramType
        : defaultDiagram;
      const lines = Array.isArray(sc?.boardLines)
        ? sc.boardLines
            .map((l: any) => String(l || '').trim())
            .filter(Boolean)
            .slice(0, 6)
        : [];
      const labels = Array.isArray(sc?.diagramLabels)
        ? sc.diagramLabels
            .map((l: any) => String(l || '').trim())
            .filter(Boolean)
            .slice(0, 4)
        : ['العنصر الأساسي', 'العلاقة العلمية', 'التطبيق والنتيجة'];
      const textbookKeyPoints = Array.isArray(sc?.textbookKeyPoints)
        ? sc.textbookKeyPoints
            .map((l: any) => String(l || '').trim())
            .filter(Boolean)
            .slice(0, 4)
        : undefined;

      const rawNarration = String(
        sc?.narration ||
          `ننتقل الآن إلى شرح الجزء رقم ${idx + 1} من درس ${params.lesson} في مادة ${params.subject} بفهم عميق وتركيز.`
      ).trim();

      return {
        id: String(sc?.id || `scene-${idx + 1}`),
        title: String(sc?.title || `المرحلة ${idx + 1}: شرح ${params.lesson}`).trim(),
        durationSec: Math.max(11, Math.min(30, Number(sc?.durationSec) || 15)),
        diagramType: diag,
        diagramTitle: String(sc?.diagramTitle || `الرسم التوضيحي — ${params.lesson}`).trim(),
        diagramLabels: labels,
        boardLines:
          lines.length > 0
            ? lines
            : [`• المحور ${idx + 1}: الفهم المنهجي لدرس ${params.lesson}`],
        formulaBox: sc?.formulaBox ? String(sc.formulaBox).trim() : undefined,
        narration: rawNarration,
        textbookKeyPoints,
      };
    });

  if (scenes.length === 0) return null;

  return {
    id: `wb-${Date.now()}`,
    subject: params.subject,
    chapter: params.chapter,
    lesson: params.lesson,
    introTitle: String(raw.introTitle || `شرح سبورة متكامل: ${params.lesson}`).trim(),
    lessonObjective: raw.lessonObjective ? String(raw.lessonObjective).trim() : undefined,
    scenes,
    source: meta.source,
    providerLabel: meta.providerLabel,
    warning: meta.warning,
    createdAt: new Date().toISOString(),
  };
}

