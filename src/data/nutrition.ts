export function getTodayEgyptDayIndex(date: Date = new Date()): number {
  // JS getDay(): 0=Sun, 1=Mon, ..., 6=Sat -> map Sat=0, Sun=1, ..., Fri=6
  return (date.getDay() + 1) % 7;
}

