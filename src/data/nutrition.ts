export function getDietPlanForDay(
  categoryKey: 'overweight' | 'balanced' | 'underweight',
  dayIndex: number
): EgyptianDietPlan {
  const basePlan = EGYPTIAN_DIET_PLANS[categoryKey];
  const pool = ROTATING_DAILY_MEALS_BY_PLAN[categoryKey] || [basePlan.meals];
  const safeIdx = ((dayIndex % pool.length) + pool.length) % pool.length;
  return {
    ...basePlan,
    meals: pool[safeIdx] || basePlan.meals,
  };
}

